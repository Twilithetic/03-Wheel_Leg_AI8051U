; =====================================================
; AI8051U 扩展中断跳转表 (中断号 > 31)
; 文件: extended_isr.asm
; 用于: Keil C251 不支持 interrupt 32+ 的解决方案
; =====================================================
; 
; 原理：Keil C251 只支持 interrupt 0~31，
; 但 AI8051U 的 DMA_ADC 中断向量为 48 (地址 0x0183)
; 
; 解决方案：在 0x0183 地址放一条跳转指令，
; 跳到 C 语言编写的普通函数 DMA_ADC_ISR()
; =====================================================

    NAME    EXTENDED_ISR

; 声明外部 C 函数
    EXTRN   CODE (DMA_ADC_ISR)

; =====================================================
; DMA_ADC 中断 (向量 48, 地址 0x0183)
; =====================================================
    CSEG    AT 0183H
    LJMP    DMA_ADC_ISR

    END
